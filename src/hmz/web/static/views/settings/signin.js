/**
 * What a way of signing in, or one thing it asks for, says of itself, in the page's language.
 *
 * @param {string} about As `accounts.list` answers it.
 * @returns {string}
 */
export function signSaid(about) {
  const said = String(about || '')
  if (said.startsWith(GATEWAY)) return t('through a local LiteLLM gateway: {way}', { way: signSaid(said.slice(GATEWAY.length)) })
  return SAID.get(said) || said
}
